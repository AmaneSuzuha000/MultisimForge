"""Simulation data extraction: run Multisim's own analyses directly on a .ms14, or run arbitrary SPICE text.

For a .ms14: copy it, place voltage probes on the nets to measure (a probe = a Multisim output variable),
then run DC operating point / AC sweep / transient analyses through COM. The netlist is generated by Multisim itself, so any component can be simulated.
Probe insertion: place a voltage probe on a wire endpoint of the target net, save a copy, then simulate through COM.
"""
