"""Component template library: harvest components from .ms14 files and look them up by name.

A component template = all objects belonging to it in the source file: the CiComponent, its CiPorts, referenced CiModels,
the schematic symbol, plus the panel state (for virtual instruments) and the RefDes record (for multi-section devices).
Circuits are generated by copying the whole group with fresh IDs, so any component that has appeared in some .ms14 can be used.
"""
