class Library:
    def __init__(self, path: Path | None = None):
        self.path = Path(path or library_dir())
        self.index_path = self.path / "index.json"
        self.index = json.loads(self.index_path.read_text(encoding="utf-8")) if self.index_path.exists() else {}
        self._lower = {k.lower(): k for k in self.index}
        self._part_cache: dict[str, ET.Element] = {}
        self._struct_cache: dict[str, ET.Element] = {}
        self._db_sections_cache: dict | None = None

    def db_section(self, name: str) -> dict | None:
        if self._db_sections_cache is None:
            p = self.path / "db_sections.json"
            if p.is_file():
                try:
                    self._db_sections_cache = json.loads(p.read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    self._db_sections_cache = {}
            else:
                self._db_sections_cache = {}
        return self._db_sections_cache.get(name)

    def save_index(self):
        self.path.mkdir(parents=True, exist_ok=True)
        tmp = self.path / f"{self.index_path.name}.tmp-{os.getpid()}-{uuid.uuid4().hex[:8]}"
        tmp.write_text(json.dumps(self.index, ensure_ascii=False, indent=1, sort_keys=True), encoding="utf-8")
        os.replace(tmp, self.index_path)
        self._lower = {k.lower(): k for k in self.index}

    def resolve(self, name: str) -> str | None:
        return self._lower.get(name.lower())

    def load(self, name: str) -> ET.Element:
        key = self.resolve(name)
        if key is None:
            raise KeyError(f"Component library has no {name!r}; search with `multisimforge parts list {name[:4]}`, "
                           f"or place the component in Multisim, save, and run `multisimforge parts harvest file.ms14`")
        cached = self._part_cache.get(key)
        if cached is None:
            cached = xmlio.parse_text(xmlio.read(self.path / self.index[key]["file"]))
            self._part_cache[key] = cached
        return xmlio.deepcopy(cached)

    def struct(self, name: str) -> ET.Element:
        """Structural templates: blank circuit shell, wires, external pins, junctions, etc."""
        cached = self._struct_cache.get(name)
        if cached is None:
            cached = xmlio.parse_text(xmlio.read(self.path / STRUCT / name))
            self._struct_cache[name] = cached
        return xmlio.deepcopy(cached)

    def add(self, part: ET.Element, force: bool = False) -> bool:
        name = part.get("Name")
        if self.resolve(name) and not force:
            return False
        if self.resolve(name):
            name = self.resolve(name)
        info = describe(part)
        rel = f"{safe_name(name)}.xml"
        self.path.mkdir(parents=True, exist_ok=True)
        xmlio.write(self.path / rel, xmlio.to_text(part))
        self._part_cache.pop(name, None)
        info["file"] = rel
        self.index[name] = info
        self._lower[name.lower()] = name
        return True

    def search(self, query: str = ""):
        q = query.lower()
        for name, info in sorted(self.index.items()):
            if not q or q in name.lower() or q in info.get("family", "").lower():
                yield name, info


def describe(part: ET.Element) -> dict:
    items = part.find("Items")
    comp = items.find("Item/CiComponent")
    ports = {it.get("CiID"): _s(it[0].get("LocalName")) for it in items if it.get("Class") == "CiPort"}
    sym = items.find("Item[@Class='CIITSymbolComp']/CIITSymbolComp")
    visible = [ports[p.get("PortID")] for p in visible_pins(sym) if p.get("PortID") in ports]
    template = spice_template(comp)
    if part.get("Kind") == "instrument":       # Instruments use the netlist pin order
        order = INSTRUMENT_PINS.get(part.get("Name"))
        visible.sort(key=lambda n: order.index(n) if order and n in order else (int(n) if n.isdigit() else 999))
    colls = _strings(comp)
    prefix = re.sub(r"%d.*", "", (colls[1][4] if len(colls) > 1 and len(colls[1]) > 4 else "")) or "U"
    secs = section_names(part)
    num_secs = int(sym.get("NumSections") or 1)
    out = {
        "family": part.get("Family"),
        "kind": part.get("Kind"),
        "prefix": prefix,
        "pins": visible if part.get("Kind") == "instrument" else spice_pin_order(template, visible),
        "hidden_pins": {h.get("Name"): h.get("Net") for h in part.findall("HiddenPin")},
        "sections": num_secs,
        "template": template.strip()[:160],
        "source": f"{part.get('Source')}:{part.get('SourceRef')}",
    }
    if len(secs) > 1 or num_secs > 1:
        out["section_names"] = secs
        out["shared_pins"] = shared_pins(part)
        out["section_pins"] = {s: section_spec(part, s)["pins"] for s in secs}
    return out


def harvest_path(target: Path, lib: Library, force: bool = False, label_root: Path | None = None) -> dict:
    """Harvest one .ms14 or an entire directory; return {added: [...], skipped: n, failed: [...]}."""
    files = sorted(target.rglob("*.ms14")) if target.is_dir() else [target]
    added, skipped, failed = [], 0, []
    # When harvesting a directory, first take the preferred instances individually (only the specified refdes for each), then harvest everything
    jobs = [(target / rel, {ref}) for rel, ref in PREFERRED if (target / rel).is_file()] if target.is_dir() else []
    jobs += [(f, None) for f in files]
    cache = {}
    for f, only in jobs:
        try:
            root = cache.get(f) or xmlio.load(f)
        except Exception as exc:          # A corrupted file does not affect the others
            failed.append(f"{f.name}: {exc}")
            continue
        if only:
            cache[f] = root
        label = f.relative_to(label_root or (target if target.is_dir() else f.parent)).as_posix()
        h = Harvester(root, label)
        comps = [it for it in h.components() if only is None or _s(it[0].get("LocalName")) in only]
        for comp_item in comps:
            try:
                part = h.extract(comp_item)
            except Exception as exc:
                failed.append(f"{label}:{_s(comp_item[0].get('LocalName'))}: {exc}")
                continue
            if part is None:
                continue
            if lib.add(part, force=force and target.is_file()):
                added.append(part.get("Name"))
            else:
                skipped += 1
    lib.save_index()
    return {"added": added, "skipped": skipped, "failed": failed}


def init_library(lib: Library) -> dict:
    """Initial library build: structural templates (the blank circuit shell is created by the local Multisim) + all components from the official NI samples."""
    from . import com, structural
    samples = Path(CONFIG["samples_dir"])
    struct_dir = lib.path / STRUCT
    struct_dir.mkdir(parents=True, exist_ok=True)
    blank = struct_dir / "blank.ms14"
    com.call({"op": "blank", "out": str(blank)})
    structural.extract(samples, struct_dir, blank)
    blank.unlink()
    return harvest_path(samples, lib, label_root=samples)


# ---------------------------------------------------------------------------
# Fetch components from the Multisim database: use COM ReplaceComponent in a carrier circuit to swap in the target component, then harvest
# ---------------------------------------------------------------------------
# A single-section 2N3904 carrier with populated RefDesPrefixUsageMap, an ASCII path,
# and a relocated OpenFile copy succeeds across analog, power, timer, diode, MOSFET,
# TTL, and CMOS families. Multi-section harvested carriers (e.g. 7404N) trigger vendor
# 0xC0000374 heap corruption inside COM ReplaceComponent and are avoided as carriers.
CARRIERS = [("Q1", "Q1 a b c 2N3904")]


def _fetch_scratch_dir(run_id: str) -> tuple[Path, bool]:
    """Pick an ASCII work directory when possible so COM OpenFile never hits non-ASCII path bugs."""
    work = Path(CONFIG["work_dir"]) / "fetch" / run_id
    if str(work).isascii():
        work.mkdir(parents=True, exist_ok=True)
        return work, False
    temp_base = Path(tempfile.gettempdir()) / "multisimforge" / "fetch" / run_id
    if str(temp_base).isascii():
        temp_base.mkdir(parents=True, exist_ok=True)
        return temp_base, True
    work.mkdir(parents=True, exist_ok=True)
    return work, False


def _rc4_jet(key: bytes, data: bytes) -> bytes:
    s = list(range(256))
    j = 0
    for i in range(256):
        j = (j + s[i] + key[i % len(key)]) & 0xFF
        s[i], s[j] = s[j], s[i]
    out = bytearray(len(data))
    i = j = 0
    for k, b in enumerate(data):
        i = (i + 1) & 0xFF
        j = (j + s[i]) & 0xFF
        s[i], s[j] = s[j], s[i]
        out[k] = b ^ s[(s[i] + s[j]) & 0xFF]
    return bytes(out)


def _jet_password(db_path: Path) -> str:
    """Decode the Jet3/Jet4 header password from MSCOMP_S.PRD in pure Python."""
    with db_path.open("rb") as f:
        hdr = bytearray(f.read(256))
    if len(hdr) < 0x98:
        raise ValueError(f"{db_path} is too small to be a Jet database")
    dec = _rc4_jet(bytes([0xC7, 0xDA, 0x39, 0x6B]), bytes(hdr[0x18:0x98]))
    if hdr[0x14] == 0:
        return dec[0x2A:0x3E].split(b"\x00", 1)[0].decode("latin-1")
    raw_pw = bytearray(dec[0x2A:0x52])
    cdate = dec[0x4A:0x4E]
    for i in range(0, 40, 2):
        raw_pw[i] ^= cdate[0] if (i // 2) % 2 == 0 else 0
    return bytes(raw_pw).decode("utf-16-le").split("\x00", 1)[0]


def _adodb_dbindex_script(db_path: Path, pw: str, out_index: Path, out_sections: Path) -> str:
    return (
        "import json, os, pythoncom, uuid, win32com.client\n"
        "from pathlib import Path\n"
        f"db_path = {str(db_path)!r}\n"
        f"pw = {pw!r}\n"
        f"out_index = Path({str(out_index)!r})\n"
        f"out_sections = Path({str(out_sections)!r})\n"
        "pythoncom.CoInitialize()\n"
        "conn = win32com.client.Dispatch('ADODB.Connection')\n"
        "conn.Open(f'Provider=Microsoft.Jet.OLEDB.4.0;Data Source={db_path};Jet OLEDB:Database Password={pw};')\n"
        "def fetch(sql):\n"
        "    rs = win32com.client.Dispatch('ADODB.Recordset')\n"
        "    rs.Open(sql, conn, 0, 1)\n"
        "    try:\n"
        "        return () if rs.EOF else rs.GetRows()\n"
        "    finally:\n"
        "        rs.Close()\n"
        "try:\n"
        "    g_rows = fetch('SELECT Family_Group_ID, Family_Group FROM SYS_CONFIGURATION_GROUPS')\n"
        "    groups = dict(zip(g_rows[0], g_rows[1])) if g_rows else {}\n"
        "    f_rows = fetch('SELECT Family_ID, Family_Name, Family_Group_ID FROM SYS_CONFIGURATION')\n"
        "    families = {fid: [groups.get(gid), fname] for fid, fname, gid in zip(*f_rows)} if f_rows else {}\n"
        "    c_rows = fetch('SELECT Component_ID, Family_ID, Component_Name FROM SYS_COMPONENT')\n"
        "    index, id_to_name = {}, {}\n"
        "    if c_rows:\n"
        "        for cid, fid, cname in zip(*c_rows):\n"
        "            f = families.get(fid)\n"
        "            if f and cname:\n"
        "                name = str(cname)\n"
        "                id_to_name[int(cid)] = name\n"
        "                if name not in index:\n"
        "                    index[name] = f\n"
        "    sym_rows = fetch('SELECT Component_ID, Sec_Order, Pinout_ANSI FROM SYS_MAPPING_COMP_SYMBOL')\n"
        "    mod_rows = fetch('SELECT Component_ID, Sec_Order, Template FROM SYS_MAPPING_COMP_MODEL')\n"
        "    by_cid = {}\n"
        "    if sym_rows:\n"
        "        for cid, sec_order, pinout in zip(*sym_rows):\n"
        "            sec_no = int(sec_order or 1)\n"
        "            letter = chr(64 + sec_no)\n"
        "            pins = [p.strip() for p in str(pinout or '').splitlines() if p.strip()]\n"
        "            by_cid.setdefault(int(cid), {})[letter] = {'pins': pins}\n"
        "    if mod_rows:\n"
        "        for cid, sec_order, tpl in zip(*mod_rows):\n"
        "            sec_no = int(sec_order or 1)\n"
        "            letter = chr(64 + sec_no)\n"
        "            entry = by_cid.setdefault(int(cid), {}).setdefault(letter, {})\n"
        "            if tpl and 'template' not in entry:\n"
        "                entry['template'] = str(tpl)\n"
        "    sections_out = {}\n"
        "    for cid, secs in by_cid.items():\n"
        "        if len(secs) > 1 and cid in id_to_name and id_to_name[cid] not in sections_out:\n"
        "            sections_out[id_to_name[cid]] = {'sections': secs}\n"
        "    out_index.parent.mkdir(parents=True, exist_ok=True)\n"
        "    for path, data in ((out_index, index), (out_sections, sections_out)):\n"
        "        tmp = path.with_name(f'.{path.name}.tmp-{os.getpid()}-{uuid.uuid4().hex[:8]}')\n"
        "        tmp.write_text(json.dumps(data, ensure_ascii=False), encoding='utf-8')\n"
        "        os.replace(tmp, path)\n"
        "    print(len(index))\n"
        "finally:\n"
        "    conn.Close()\n"
    )


def build_db_index(lib: Library) -> dict:
    """Read MSCOMP_S.PRD via pure-Python Jet3/4 + ADODB on Windows (Node decoder fallback)."""
    out = lib.path / "db_index.json"
    out_sections = lib.path / "db_sections.json"
    db_path = Path(CONFIG["master_db"])
    py32 = python32_argv()
    if sys.platform == "win32" and db_path.is_file() and py32 and py32[0]:
        try:
            pw = _jet_password(db_path)
            script = _adodb_dbindex_script(db_path, pw, out, out_sections)
            r = subprocess.run([*py32, "-c", script], stdin=subprocess.DEVNULL,
                               capture_output=True, text=True, timeout=900)
            if r.returncode == 0:
                return {"components": int(r.stdout.strip() or 0), "index": str(out),
                        "sections_index": str(out_sections), "backend": "adodb"}
            adodb_err = (r.stderr or r.stdout or "").strip()[-500:]
        except (OSError, ValueError, subprocess.SubprocessError) as exc:
            adodb_err = str(exc)
        if not (shutil.which("node") and Path(CONFIG.get("node_decoder", "")).is_dir()):
            raise RuntimeError(f"Failed to read the master component database: {adodb_err}")
    r = subprocess.run(["node", str(ROOT / "tools" / "dbindex.js"), CONFIG["master_db"], str(out),
                        CONFIG["node_decoder"]], stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=900)
    if r.returncode != 0:
        raise RuntimeError(f"Failed to read the master component database: {r.stderr.strip()[-500:]}")
    return {"components": int(r.stdout.strip() or 0), "index": str(out), "backend": "node"}


def db_lookup(lib: Library, name: str):
    path = lib.path / "db_index.json"
    if not path.exists():
        build_db_index(lib)
    index = json.loads(path.read_text(encoding="utf-8"))
    hit = index.get(name) or next((v for k, v in index.items() if k.lower() == name.lower()), None)
    if hit is None:
        close = [k for k in index if name.lower() in k.lower()][:15]
        raise KeyError(f"Multisim database has no {name!r}; close matches: {close}")
    return hit


def _replace_with_restart(carrier, ref, group, family, name, out, tried):
    """Run one replacement, restarting the COM instance once if Multisim dies mid-job."""
    from . import com
    job = {"op": "replace", "ms14": str(carrier), "ref": ref, "group": group,
           "family": family, "name": name, "out": str(out)}
    try:
        return com.call(job, timeout=180)
    except com.ComError as exc:
        if (not isinstance(exc, com.JobIndeterminate)
                and "3221226356" not in str(exc) and "0xc0000374" not in str(exc).lower()):
            raise
    com.stop()                                        # drop the corrupted daemon and any orphaned Multisim process
    out.unlink(missing_ok=True)                        # never accept a partial file from a crashed replacement
    tried.append(f"{ref}: Multisim COM worker disconnected or crashed (0xC0000374) inside ReplaceComponent; restarted and retried")
    try:
        return com.call(job, timeout=180)
    except com.JobIndeterminate:
        com.stop()
        raise


def fetch(name: str, lib: Library, group=None, family=None) -> dict:
    from . import builder, com
    from .result import new_run_id
    if lib.resolve(name):
        return {"name": lib.resolve(name), "already": True}
    if not (group and family):
        group, family = db_lookup(lib, name)
    scratch, cleanup_scratch = _fetch_scratch_dir(new_run_id())
    tried = []
    try:
        for ref, line in CARRIERS:
            built = scratch / f"src_{ref}.ms14"
            # Opening the relocated copy (path != CIRToInfoMap RefDes path) makes Multisim
            # rebind CIITHierRefDes cleanly instead of crashing 0xC0000374 in ReplaceComponent.
            carrier = scratch / f"open_{ref}.ms14"
            builder.build({"netlist": line, "output": str(built), "layout": {ref: [300, 300]}}, lib)
            shutil.copy2(built, carrier)
            out = scratch / f"{safe_name(name)}_{safe_name(ref)}.ms14"
            out.unlink(missing_ok=True)
            try:
                _replace_with_restart(carrier, ref, group, family, name, out, tried)
            except com.ComError as exc:
                tried.append(f"{ref}: {exc}")
                continue
            if not out.is_file():
                tried.append(f"{ref}: ReplaceComponent returned but wrote no output file")
                continue
            root = xmlio.load(out)
            h = Harvester(root, f"Multisim database {group}/{family}")
            for comp_item in h.components():
                part = h.extract(comp_item)
                if part is not None and part.get("Name").lower() == name.lower():
                    lib.add(part)
                    lib.save_index()
                    return {"name": part.get("Name"), "group": group, "family": family, **describe(part)}
            tried.append(f"{ref}: {name} not found in the file after replacement")
        raise RuntimeError(f"Failed to fetch {name} ({group}/{family}): {tried}")
    finally:
        if cleanup_scratch:
            shutil.rmtree(scratch, ignore_errors=True)